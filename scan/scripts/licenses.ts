/**
 * Records the licence of every Go module that ends up in the upzy-scan binary, in scan/THIRD_PARTY_LICENSES.md.
 *
 *   bun scan/scripts/licenses.ts           write the file
 *   bun scan/scripts/licenses.ts --check   fail if the file is out of date, or a module has a licence we do not recognise
 *
 * The licence is read from each module's own LICENSE file, so a dependency that changes its terms shows up as a diff.
 * A copyleft licence (GPL, AGPL, LGPL) or a licence this script cannot identify fails the run until someone has looked.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const scanDir = join(import.meta.dir, "..");
const outFile = join(scanDir, "THIRD_PARTY_LICENSES.md");

const listed = Bun.spawnSync(
  [
    "go",
    "list",
    "-deps",
    "-f",
    "{{with .Module}}{{if not .Main}}{{.Path}}|{{.Version}}|{{.Dir}}{{end}}{{end}}",
    ".",
  ],
  { cwd: scanDir, env: { ...process.env, GOFLAGS: "-mod=mod" } },
);
if (listed.exitCode !== 0) {
  console.error(listed.stderr.toString());
  process.exit(1);
}

const rules: [string, RegExp][] = [
  ["MPL-2.0", /Mozilla Public License,? (Version |v\.? ?)2\.0/i],
  ["AGPL-3.0", /GNU AFFERO GENERAL PUBLIC LICENSE/i],
  ["LGPL", /^\s*(GNU LESSER GENERAL PUBLIC LICENSE|GNU LIBRARY GENERAL PUBLIC LICENSE)/i],
  ["GPL", /^\s*GNU GENERAL PUBLIC LICENSE/i],
  ["Apache-2.0", /Apache License[\s\S]{0,40}Version 2\.0/i],
  ["MIT", /Permission is hereby granted, free of charge|The MIT License/i],
  ["ISC", /Permission to use, copy, modify, and\/or distribute this software/i],
  ["BSD-3-Clause", /Redistribution and use in source and binary forms[\s\S]*Neither the name/i],
  ["BSD-2-Clause", /Redistribution and use in source and binary forms/i],
  ["Unlicense", /This is free and unencumbered software released into the public domain/i],
  ["CC0-1.0", /CC0 1\.0 Universal/i],
  [
    "0BSD",
    /Permission to use, copy, modify, and\/or distribute this software for any purpose with or without fee/i,
  ],
];
const copyleft = new Set(["AGPL-3.0", "LGPL", "GPL"]);

/** Modules whose licence a person has read where the script cannot. Say where it was read. */
const reviewed: Record<string, string> = {
  "github.com/censys/censys-sdk-go": "MIT (README badge; the module has no LICENSE file)",
  // nuclei pulls this in for its LDAP protocol server. It is GPL-2.0, so Upzy does not distribute a built upzy-scan
  // (see README.md): people who run it build it from source. Revisit before ever publishing binaries.
  "github.com/projectdiscovery/ldapserver": "GPL-2.0 (reviewed: binaries are not distributed)",
};

function licenceOf(dir: string): string {
  let names: string[] = [];
  try {
    names = readdirSync(dir, { withFileTypes: true })
      .filter((e) => e.isFile() && /^(licen[sc]e|copying|unlicense)/i.test(e.name))
      .map((e) => e.name);
  } catch {
    return "UNKNOWN (no files)";
  }
  const found = new Set<string>();
  for (const n of names) {
    const text = readFileSync(join(dir, n), "utf8");
    for (const [id, re] of rules) {
      if (re.test(text)) {
        found.add(id);
        break;
      }
    }
  }
  return found.size ? [...found].sort().join(" AND ") : "UNKNOWN";
}

// `go list -deps` prints one line per package; a module is listed once.
const rows = [...new Set(listed.stdout.toString().split("\n").filter(Boolean))]
  .map((l) => {
    const [path, version, dir] = l.split("|");
    const licence =
      reviewed[path!] ?? (existsSync(dir!) ? licenceOf(dir!) : "UNKNOWN (not downloaded)");
    return { path: path!, version: version!, licence };
  })
  .sort((a, b) => a.path.localeCompare(b.path));

const totals = new Map<string, number>();
for (const r of rows) totals.set(r.licence, (totals.get(r.licence) ?? 0) + 1);

const md = [
  "# Third-party licences in upzy-scan",
  "",
  "Generated by `bun scan/scripts/licenses.ts`. Do not edit by hand. Every Go module that is compiled into the",
  "binary is listed with the licence found in its own LICENSE file. nuclei itself is MIT-licensed; the vendored",
  "template files and their licence are described in `templates/UPSTREAM.md`.",
  "",
  "## Summary",
  "",
  ...[...totals].sort((a, b) => b[1] - a[1]).map(([l, n]) => `- ${l}: ${n}`),
  "",
  "## Modules",
  "",
  "| Module | Version | Licence |",
  "| --- | --- | --- |",
  ...rows.map((r) => `| ${r.path} | ${r.version} | ${r.licence} |`),
  "",
].join("\n");

const bad = rows.filter(
  (r) =>
    !(r.path in reviewed) &&
    (r.licence.startsWith("UNKNOWN") || [...copyleft].some((c) => r.licence.includes(c))),
);
if (bad.length) {
  console.error("Licences that need a person to look at them:");
  for (const r of bad) console.error(`  ${r.path} ${r.version}: ${r.licence}`);
}

if (process.argv.includes("--check")) {
  const current = existsSync(outFile) ? readFileSync(outFile, "utf8") : "";
  if (current !== md) {
    console.error(
      "scan/THIRD_PARTY_LICENSES.md is out of date: run `bun scan/scripts/licenses.ts` and commit it.",
    );
    process.exit(1);
  }
  if (bad.length) process.exit(1);
  console.log(`${rows.length} modules, licences recorded`);
} else {
  writeFileSync(outFile, md);
  console.log(`wrote ${rows.length} modules to ${outFile}`);
  if (bad.length) process.exit(1);
}
