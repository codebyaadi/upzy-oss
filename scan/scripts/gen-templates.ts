/**
 * Writes scan/templates/upzy/*.yaml from the exposed-path list in packages/security, so the nuclei scanner looks for
 * exactly what the built-in check looks for, with the same wording, severities and body patterns. Never edit those
 * files by hand: change the list, run this, commit.
 *
 *   bun scan/scripts/gen-templates.ts            rewrite
 *   bun scan/scripts/gen-templates.ts --check    fail if the files differ (CI)
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { EXPOSED_PATHS } from "../../packages/security/src/checks/active";

const dir = join(import.meta.dir, "../templates/upzy");

const slug = (path: string) =>
  path
    .replace(/^\//, "")
    .replace(/[^a-zA-Z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .toLowerCase();
const y = (s: string) => JSON.stringify(s); // a JSON string is a valid YAML double-quoted scalar
const sq = (s: string) => `'${s.replace(/'/g, "''")}'`;

/** JS and RE2 agree on everything the list uses; the flags become an inline group. */
function re2(r: RegExp): string {
  const flags = [...r.flags].filter((f) => "ims".includes(f)).join("");
  const unsupported = [...r.flags].filter((f) => !"ims".includes(f));
  if (unsupported.length)
    throw new Error(`regex flags ${unsupported.join("")} are not supported: ${r}`);
  return (flags ? `(?${flags})` : "") + r.source;
}

export function generate(): Record<string, string> {
  const out: Record<string, string> = {};
  const seen = new Set<string>();
  for (const p of EXPOSED_PATHS) {
    const s = slug(p.path);
    if (seen.has(s)) throw new Error(`two exposed paths share the id ${s}`);
    seen.add(s);
    out[`exposure-${s}.yaml`] = [
      "# Generated by scan/scripts/gen-templates.ts from packages/security/src/checks/active.ts. Do not edit.",
      `id: upzy-exposure-${s}`,
      "info:",
      `  name: ${y(`${p.title} (${p.path})`)}`,
      "  author: upzy",
      `  severity: ${p.severity}`,
      `  description: ${y(p.why)}`,
      `  remediation: ${y(p.fix)}`,
      "  tags: upzy,exposure",
      "  metadata:",
      "    upzy-check-key: exposure.path",
      `    upzy-subject: ${y(p.path)}`,
      "http:",
      "  - method: GET",
      "    path:",
      `      - ${y(`{{BaseURL}}${p.path}`)}`,
      "    max-size: 20000",
      "    matchers-condition: and",
      "    matchers:",
      "      - type: status",
      "        status:",
      "          - 200",
      "      - type: regex",
      "        part: body",
      "        regex:",
      `          - ${sq(re2(p.looksLike))}`,
      "",
    ].join("\n");
  }
  return out;
}

if (import.meta.main) {
  const wanted = generate();
  if (process.argv.includes("--check")) {
    const problems: string[] = [];
    for (const [name, text] of Object.entries(wanted)) {
      const path = join(dir, name);
      if (!existsSync(path)) problems.push(`${name} is missing`);
      else if (readFileSync(path, "utf8").replace(/\r\n/g, "\n") !== text)
        problems.push(`${name} is out of date`);
    }
    if (existsSync(dir))
      for (const name of readdirSync(dir))
        if (!(name in wanted)) problems.push(`${name} is not generated any more`);
    if (problems.length) {
      console.error(
        `scan/templates/upzy does not match the exposed-path list:\n  ${problems.join("\n  ")}`,
      );
      console.error("Run `bun scan/scripts/gen-templates.ts` and commit the result.");
      process.exit(1);
    }
    console.log("scan/templates/upzy is up to date");
  } else {
    mkdirSync(dir, { recursive: true });
    if (existsSync(dir))
      for (const name of readdirSync(dir))
        if (name.endsWith(".yaml") && !(name in wanted)) rmSync(join(dir, name));
    for (const [name, text] of Object.entries(wanted)) writeFileSync(join(dir, name), text);
    console.log(`wrote ${Object.keys(wanted).length} templates to scan/templates/upzy`);
  }
}
